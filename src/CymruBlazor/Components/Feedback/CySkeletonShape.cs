namespace CymruBlazor.Components.Feedback;

/// <summary>The shape a <see cref="CySkeleton"/> placeholder takes.</summary>
public enum CySkeletonShape
{
    /// <summary>One or more bars of text (see <see cref="CySkeleton.Lines"/>).</summary>
    Text = 0,

    /// <summary>A block, for an image, chart or card.</summary>
    Rectangle = 1,

    /// <summary>A circle, for an avatar.</summary>
    Circle = 2
}
